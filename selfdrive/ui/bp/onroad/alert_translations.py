# Dynamic alert templates. Values such as speed, temperature, percentages, and
# daemon names are captured from the original alert and inserted unchanged.
_DYNAMIC_PATTERNS = (
  (re.compile(r"Drive above (.+) to engage"), tr_noop("Drive above {} to engage")),
  (re.compile(r"Steer Assist Unavailable Below (.+)"), tr_noop("Steer Assist Unavailable Below {}")),
  (re.compile(r"(Calibrating|Recalibrating): (\d+)%"), tr_noop("{}: {}%")),
  (re.compile(r"Drive Above (.+)"), tr_noop("Drive Above {}")),
  (re.compile(r"(\d+) seconds? remaining\. Press again to save early\."),
   tr_noop("{} seconds remaining. Press again to save early.")),
  (re.compile(r"(\d+(?:\.\d+)?)% full"), tr_noop("{}% full")),
  (re.compile(r"Speed Error: (-?\d+(?:\.\d+)?) m/s"), tr_noop("Speed Error: {} m/s")),
  (re.compile(r"Remount Device \(Pitch: (-?\d+(?:\.\d+)?)°, Yaw: (-?\d+(?:\.\d+)?)°\)"),
   tr_noop("Remount Device (Pitch: {}°, Yaw: {}°)")),
  (re.compile(r"Angle offset too high \(Offset: (-?\d+(?:\.\d+)?)°\)"),
   tr_noop("Angle offset too high (Offset: {}°)")),
  (re.compile(r"Steering rack geometry may be off \(Ratio: (-?\d+(?:\.\d+)?)\)"),
   tr_noop("Steering rack geometry may be off (Ratio: {})")),
  (re.compile(r"Check tires, pressure, or alignment \(Factor: (-?\d+(?:\.\d+)?)\)"),
   tr_noop("Check tires, pressure, or alignment (Factor: {})")),
  (re.compile(r"(-?\d+(?:\.\d+)?) °C"), tr_noop("{} °C")),
  (re.compile(r"(\d+(?:\.\d+)?)% used"), tr_noop("{}% used")),
  (re.compile(r"(\d+(?:\.\d+)?)% frames dropped"), tr_noop("{}% frames dropped")),
  (re.compile(r"Gas: (-?\d+)%, Steer: (-?\d+)%"), tr_noop("Gas: {}%, Steer: {}%")),
  (re.compile(r"Driving Personality: (.+)"), tr_noop("Driving Personality: {}")),
  (re.compile(r"Adjusting to (\d+ (?:km/h|mph)) speed limit"), tr_noop("Adjusting to {} speed limit")),
  (re.compile(r"Speed Limit Assist: set to (\d+ (?:km/h|mph)) to engage"),
   tr_noop("Speed Limit Assist: set to {} to engage")),
)


def translate_alert_text(text: str) -> str:
  """Translate selfdrived alert text at the UI boundary."""
  if not text:
    return text

  translated = tr(text)
  if translated != text:
    return translated

  for pattern, template in _DYNAMIC_PATTERNS:
    match = pattern.fullmatch(text)
    if match is None:
      continue

    values = list(match.groups())
    if template == "{}: {}%":
      values[0] = tr(values[0])
    elif template == "Driving Personality: {}":
      values[0] = tr(values[0])
    return tr(template).format(*values)

  return text
